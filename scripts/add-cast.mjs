/* ---------- A. 别名：把剧中名映射到已有的卡 ---------- */
const ALIAS = {
  近视眼勇闯恐怖游戏: { 思思: "思思（女儿）", 大Boss: "大Boss（老公）", 明神: "明神（传说）" },
  西游之众佛腐烂: { 观音: "观音菩萨" },
  吃人心的小妖怪: { 神像: "土庙神像" },
  俺妈和她的丧尸闺女: { 王红梅: "俺妈" },
};

const files = (await readdir(DIR)).filter((f) => f.endsWith(".json"));
let addedCards = 0, addedAlias = 0;

for (const f of files) {
  const p = path.join(DIR, f);
  const play = JSON.parse(stripBOM(await readFile(p, "utf8")));
  const title = play.title;
  play.cast = play.cast || {};

  const newCards = ADD[title] || {};
  for (const [k, v] of Object.entries(newCards)) {
    if (!play.cast[k]) { play.cast[k] = v; addedCards++; }
  }

  const aliases = ALIAS[title] || {};
  for (const [alias, canonical] of Object.entries(aliases)) {
    if (play.cast[canonical] && !play.cast[alias]) {
      play.cast[alias] = play.cast[canonical];
      addedAlias++;
    }
  }

  if (!DRY) await writeFile(p, JSON.stringify(play, null, 2), "utf8");
}

console.log(DRY ? "[dry-run] 未写盘" : "✓ 已写回 data/plays/");
console.log(`新增人物卡 ${addedCards} 张 ｜ 补别名 ${addedAlias} 个`);
